const _expectedPin = '0qSzTnEc4L9Xt6VWo4jWXFuphwaF7SEEsdYZzI0+qUQ=';

void main() {
  group('computeSpkiPinForTest', () {
    test('extracts correct SPKI pin from a known RSA-2048 v3 cert', () {
      expect(computeSpkiPinForTest(_testCertDer), _expectedPin);
    });

    test('returns null for completely invalid input', () {
      expect(computeSpkiPinForTest([0x00, 0x01, 0x02]), isNull);
    });

    test('returns null for empty input', () {
      expect(computeSpkiPinForTest([]), isNull);
    });

    test('returns null when outer tag is not SEQUENCE', () {
      // Flip first byte from 0x30 to 0x02 (INTEGER) — not a SEQUENCE
      final bad = List<int>.from(_testCertDer)..[0] = 0x02;
      expect(computeSpkiPinForTest(bad), isNull);
    });

    test('returns a 44-character base64 string for a valid cert', () {
      final pin = computeSpkiPinForTest(_testCertDer);
      expect(pin, isNotNull);
      // SHA-256 = 32 bytes → base64 = 44 chars (with padding)
      expect(pin!.length, 44);
    });

    test('different certs produce different pins', () {
      // Flip a byte inside the public key body — should produce a different hash
      final mutated = List<int>.from(_testCertDer);
      // Byte ~200 is well inside the RSA public key body
      mutated[200] = mutated[200] ^ 0xff;
      final mutatedPin = computeSpkiPinForTest(mutated);
      // Parser may or may not succeed (length fields may still be intact),
      // but if it does the pin must differ.
      if (mutatedPin != null) {
        expect(mutatedPin, isNot(_expectedPin));
      }
    });
  });
}
